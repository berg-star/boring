const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = (process.env.BASE_URL || 'http://127.0.0.1:18080').replace(/\/$/, '');
(async () => {
  fs.mkdirSync('.qa', { recursive: true });
  const browser = await chromium.launch(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : { channel: 'chrome' });
  try {
    const contexts = await Promise.all([0, 1].map(() => browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' })));
    const host = await contexts[0].newPage();
    let guest = await contexts[1].newPage();
    const errors = [];
    for (const page of [host, guest]) page.on('pageerror', e => errors.push(e.message));
    await host.goto(base + '/land-online.html');
    await host.locator('#land-create').tap();
    await host.waitForFunction(() => document.querySelector('#land-board').dataset.run);
    const link = await host.locator('#land-share-link').inputValue();
    const code = await host.locator('#land-room-code').textContent();
    assert.match(link, new RegExp('room=' + code));
    assert.equal(await host.locator('#land-ready').isDisabled(), true);
    await guest.goto(link);
    assert.equal(await guest.locator('#land-code').inputValue(), code);
    await guest.locator('#land-join-form button').tap();
    await host.waitForFunction(() => !document.querySelector('#land-ready').disabled);
    await guest.waitForFunction(() => !document.querySelector('#land-ready').disabled);
    assert.equal((await contexts[1].request.post(base + '/api/land/join', { data: { room: code } })).status(), 409);
    await host.locator('#land-ready').tap();
    assert.equal(await host.locator('#land-board').getAttribute('data-phase'), 'waiting');
    await guest.locator('#land-ready').tap();
    for (const page of [host, guest]) await page.waitForFunction(() => document.querySelector('#land-board').dataset.phase === 'playing');
    assert.equal(await host.locator('#land-room-info').evaluate(e => e.open), false);
    assert.equal(await guest.locator('.land-edge:not(:disabled)').count(), 0);
    async function move(edge) {
      const before = Number(await host.locator('#land-board').getAttribute('data-ply'));
      const side = Number(await host.locator('#land-board').getAttribute('data-turn'));
      const page = side ? guest : host;
      await page.locator(`[data-edge="${edge}"]`).tap();
      for (const peer of [host, guest]) await peer.waitForFunction(ply => Number(document.querySelector('#land-board').dataset.ply) === ply, before + 1);
      assert.equal(await host.locator(`.land-line`).nth(edge).getAttribute('data-owner'), String(side));
      assert.deepEqual(await host.locator('.land-box').evaluateAll(nodes => nodes.map(n => n.dataset.owner)), await guest.locator('.land-box').evaluateAll(nodes => nodes.map(n => n.dataset.owner)));
    }
    for (const edge of [0, 1, 3, 4, 12, 14, 13]) await move(edge);
    assert.equal(await host.locator('#land-score-left').textContent(), '2');
    assert.equal(await host.locator('#land-board').getAttribute('data-turn'), '0');
    assert.match(await host.locator('#land-status').textContent(), /两块.*继续画/);
    assert.equal(await host.locator('.land-box[data-owner="0"]').count(), 2);
    for (const theme of ['lime', 'cream', 'violet', 'ocean']) {
      await host.locator('.theme-trigger').tap();
      await host.locator(`[data-theme-choice="${theme}"]`).tap();
      await host.locator('.theme-close').tap();
      assert.equal(await host.locator('#land-score-left').textContent(), '2');
      for (const width of [320, 390, 844, 1440]) {
        await host.setViewportSize({ width, height: 844 });
        assert.equal(await host.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, theme + ' ' + width);
        assert.equal(await host.locator('.land-edge').evaluateAll(nodes => nodes.every(n => n.getBoundingClientRect().width >= 44 && n.getBoundingClientRect().height >= 44)), true);
      }
    }
    await host.setViewportSize({ width: 390, height: 844 });
    await host.locator('#land-sound').tap();
    assert.equal(await host.locator('#land-sound').getAttribute('aria-pressed'), 'false');
    await host.locator('#land-board').scrollIntoViewIfNeeded();
    await host.screenshot({ path: '.qa/land-mobile.png' });
    await guest.close();
    await host.waitForFunction(() => document.querySelector('#land-connection-right').textContent === '离线');
    assert.equal(await host.locator('.land-edge:not(:disabled)').count(), 0);
    guest = await contexts[1].newPage();
    guest.on('pageerror', e => errors.push(e.message));
    await guest.goto(link);
    await guest.waitForFunction(() => document.querySelector('#land-board').dataset.ply === '7');
    await host.waitForFunction(() => document.querySelector('#land-connection-right').textContent === '在线');
    await host.reload();
    await host.waitForFunction(() => document.querySelector('#land-board').dataset.ply === '7');
    assert.equal(await host.locator('#land-score-left').textContent(), '2');
    assert.equal(await host.locator('#land-sound').getAttribute('aria-pressed'), 'false');
    for (const edge of [2, 5, 15, 6, 7, 8, 9, 10, 11, 16, 17, 18, 19, 20, 21, 22, 23]) await move(edge);
    assert.equal(await host.locator('#land-board').getAttribute('data-phase'), 'finished');
    assert.equal(await host.locator('.land-edge:not(:disabled)').count(), 0);
    assert.equal(await host.locator('#land-result').isVisible(), true);
    assert.equal(Number(await host.locator('#land-score-left').textContent()) + Number(await host.locator('#land-score-right').textContent()), 9);
    await host.locator('#land-ready').tap();
    assert.equal(await host.locator('#land-board').getAttribute('data-phase'), 'finished');
    await guest.locator('#land-ready').tap();
    await host.waitForFunction(() => document.querySelector('#land-board').dataset.phase === 'playing' && document.querySelector('#land-board').dataset.ply === '0');
    await guest.waitForFunction(() => document.querySelector('#land-board').dataset.phase === 'playing' && document.querySelector('#land-board').dataset.ply === '0');
    assert.equal(await host.locator('#land-board').getAttribute('data-turn'), '1');
    assert.equal(await host.locator('.land-edge:not(:disabled)').count(), 0);
    assert.equal(await guest.locator('.land-edge:not(:disabled)').count(), 24);
    await guest.locator('#land-leave').tap();
    await host.waitForFunction(() => document.querySelector('#land-board').dataset.phase === 'waiting');
    await host.locator('#land-leave').tap();
    await host.locator('#land-code').fill('OOOOOO');
    await host.locator('#land-join-form button').tap();
    assert.match(await host.locator('#land-error').textContent(), /六位/);
    await host.goto(base + '/harmony-online.html');
    await host.goto(base + '/luggage.html');
    await host.locator('#export-text').tap();
    await host.waitForFunction(() => document.querySelector('#export-text-value').value.length > 0);
    const records = JSON.parse(await host.locator('#export-text-value').inputValue()).records;
    assert.ok(records.some(r => r.key === 'boring-lab-land-sound' && r.value === 'off'));
    const visits = JSON.parse(records.find(r => r.key === 'boring-lab-achievements-v1').value).visits;
    assert.ok(visits.includes('land-online') && visits.includes('harmony-online'));
    await host.goto(base + '/land-online.html');
    await host.waitForFunction(() => !!navigator.serviceWorker.controller);
    await contexts[0].setOffline(true);
    await host.reload();
    await host.locator('#land-create').tap();
    await host.waitForFunction(() => !document.querySelector('#land-error').hidden);
    assert.match(await host.locator('#land-error').textContent(), /检查网络/);
    await contexts[0].setOffline(false);
    assert.deepEqual(errors, []);
    console.log('PASS: two phones, touch/roles, double capture, four palettes, 44px targets, resume/reload, full match, swapped opener, sound and luggage records at ' + base);
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });